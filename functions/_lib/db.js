/* functions/_lib/db.js
 *
 * All database access lives here. Endpoints never touch env.DB directly, so
 * there is one place to check that queries are parameterised and that the clue
 * bank is only ever read server-side.
 *
 * If the D1 binding is missing — which it will be until the dashboard step in
 * the README is done — every function falls back to the small development
 * dataset in data/sample-clues.js. The API contract is identical either way,
 * so connecting D1 later changes nothing in the browser.
 */

import { SAMPLE_PUZZLES } from "./sample-puzzles.js";

export function hasDB(env) {
  return !!(env && env.DB && typeof env.DB.prepare === "function");
}

/* Puzzles are pre-generated by tools/build_puzzles.js and stored whole.
   Generating a crossword takes roughly 900ms of CPU, which is far past what a
   Worker should spend per request; reading one back is a single indexed SELECT.
   See README "Why puzzles are pre-generated". */
export async function getDailyPuzzle(env, dailyNo) {
  if (!hasDB(env)) {
    const list = SAMPLE_PUZZLES.daily;
    return list[(dailyNo - 1) % list.length] || null;
  }
  const row = await env.DB
    .prepare("SELECT payload FROM puzzles WHERE mode = 'daily' AND daily_no = ? LIMIT 1")
    .bind(dailyNo)
    .first();
  return row ? JSON.parse(row.payload) : null;
}

/* Practice draws from a pre-generated pool. The browser asks for "a new
   practice game" and the server decides which one — the pool never leaves the
   server, and no client-side selection over the bank is possible. */
export async function getPracticePuzzle(env, opts = {}) {
  const { category = null, seenIds = [], usedClues = null } = opts;

  if (!hasDB(env)) {
    const list = category
      ? SAMPLE_PUZZLES.practice.filter((p) => p.category === category)
      : SAMPLE_PUZZLES.practice;
    const pick = list[Math.floor(Math.random() * list.length)];
    return pick ? { ...pick, rowId: pick.rowId } : null;
  }

  /* Pick by what the player has not read, not merely what they have not been
     served. Two cheap queries: the id and clue list of every candidate (a few
     hundred short rows), then the payload of the one chosen. Unpacking every
     payload to compare would mean reading megabytes per request. */
  if (usedClues && usedClues.length) {
    const used = new Set(usedClues);
    let sql = "SELECT id, clue_ids FROM puzzles WHERE mode = 'practice'";
    const binds = [];
    if (category) { sql += " AND category = ?"; binds.push(category); }
    const all = await env.DB.prepare(sql).bind(...binds).all();
    const cands = (all.results || []).filter((r) => r.clue_ids);
    if (cands.length) {
      let best = null, bestScore = Infinity;
      for (const c of cands) {
        let ids;
        try { ids = JSON.parse(c.clue_ids); } catch (e) { continue; }
        let overlap = 0;
        for (const id of ids) if (used.has(id)) overlap++;
        // Ties broken at random, or every player walks the pool in step.
        const score = overlap + Math.random() * 0.5;
        if (score < bestScore) { bestScore = score; best = c; }
      }
      if (best) {
        const row = await env.DB
          .prepare("SELECT id, payload FROM puzzles WHERE id = ?").bind(best.id).first();
        if (row) return { ...JSON.parse(row.payload), rowId: row.id,
                          fresh: Math.round(bestScore) === 0 };
      }
    }
  }

  // Fall back to avoiding pool entries this browser has recently been served.
  const recent = seenIds.slice(0, 40).filter((n) => Number.isInteger(n));
  const holes = recent.map(() => "?").join(",");

  // Select the table's own primary key, not anything inside the payload: the
  // token has to name the row that getPuzzleForToken() will look up.
  let sql = "SELECT id, payload FROM puzzles WHERE mode = 'practice'";
  const binds = [];
  if (category) { sql += " AND category = ?"; binds.push(category); }
  if (recent.length) { sql += ` AND id NOT IN (${holes})`; binds.push(...recent); }
  sql += " ORDER BY RANDOM() LIMIT 1";

  let row = await env.DB.prepare(sql).bind(...binds).first();
  if (!row && recent.length) {
    // The pool ran out of unseen puzzles for this filter: fall back rather than
    // hand the player nothing.
    const retry = "SELECT id, payload FROM puzzles WHERE mode = 'practice'" +
      (category ? " AND category = ?" : "") + " ORDER BY RANDOM() LIMIT 1";
    row = await env.DB.prepare(retry).bind(...(category ? [category] : [])).first();
  }
  if (!row) return null;
  return { ...JSON.parse(row.payload), rowId: row.id };
}

/* Answers are read only to settle a check or an explicit reveal, and only for
   the single entry asked about. */
export async function getPuzzleForToken(env, token) {
  const t = parseToken(token);
  if (!t) return null;
  if (t.mode === "daily") return getDailyPuzzle(env, t.id);
  /* A themed token names a board that is already out. Without the release
     guard here, check-answer and reveal would read answers straight out of a
     board scheduled for a Friday six weeks away — the same leak as the daily,
     through a door nobody had thought to lock. */
  if (t.mode === "theme") return getThemeBoard(env, t.id);

  if (!hasDB(env)) {
    return SAMPLE_PUZZLES.practice.find((p) => String(p.rowId) === String(t.id)) || null;
  }
  /* Retired rows are still resolvable BY NAME, and only by name. Retiring the
     pool is `mode = 'practice_retired'`, which every selection query above
     filters out — so no new practice game can reach one. This lookup is the
     other half: a player holding a saved board has its token already, and
     without this their game turns into "that practice puzzle is no longer
     stored" mid-solve. Naming a retired board grants nothing a fresh request
     would not have granted the day before it was retired. */
  const row = await env.DB
    .prepare("SELECT payload FROM puzzles WHERE mode IN ('practice', 'practice_retired') AND id = ? LIMIT 1")
    .bind(Number(t.id))
    .first();
  return row ? JSON.parse(row.payload) : null;
}

/* Tokens name a stored puzzle. They carry no answer material and are not
   secrets — they exist so check-answer knows which puzzle is being played,
   not to authorise anything. */
export function makeToken(mode, id) {
  return `${mode}:${id}`;
}

export function parseToken(token) {
  const m = /^(daily|practice|theme):(\d+)$/.exec(String(token || ""));
  return m ? { mode: m[1], id: Number(m[2]) } : null;
}

/* Today, as the server reckons it. Themed boards are released on a date, and
   the date has to be decided here for the same reason a daily is: the browser
   and the server disagree about which day it is for part of every day outside
   UTC, so a board released by the client's clock would appear early for some
   players and late for others. */
export function serverToday() {
  return new Date().toISOString().slice(0, 10);
}

/* A themed board, by row id, and only once it has been released. An unreleased
   board is treated as though it does not exist rather than refused with a
   different message: "not yet" and "no such board" should look identical from
   outside, or the reply itself tells you what is coming. */
export async function getThemeBoard(env, id, { includeUnreleased = false } = {}) {
  if (!hasDB(env)) return null;
  const row = await env.DB.prepare(
    `SELECT b.id, b.theme_id, b.board_no, b.release_on, b.payload, t.name AS theme_name
       FROM theme_boards b JOIN themes t ON t.id = b.theme_id
      WHERE b.id = ? LIMIT 1`).bind(Number(id)).first();
  if (!row) return null;
  if (!includeUnreleased && row.release_on > serverToday()) return null;
  const payload = JSON.parse(row.payload);
  return Object.assign(payload, {
    boardId: row.id, themeId: row.theme_id, themeName: row.theme_name,
    boardNo: row.board_no, releaseOn: row.release_on,
  });
}

export async function listCategories(env) {
  if (!hasDB(env)) {
    return [...new Set(SAMPLE_PUZZLES.practice.map((p) => p.category).filter(Boolean))];
  }
  const res = await env.DB
    .prepare("SELECT DISTINCT category FROM puzzles WHERE mode = 'practice' AND category IS NOT NULL")
    .all();
  return (res.results || []).map((r) => r.category);
}

/* How many clues the practice pool can reach. Not the whole bank: a clue only
   becomes reachable once some pre-generated puzzle uses it, so this is the
   honest denominator for "clues seen". */
export async function bankSize(env) {
  if (!hasDB(env)) return 0;
  const rows = await env.DB
    .prepare("SELECT clue_ids FROM puzzles WHERE mode = 'practice' AND clue_ids IS NOT NULL")
    .all();
  const ids = new Set();
  for (const r of rows.results || []) {
    try { JSON.parse(r.clue_ids).forEach((id) => ids.add(id)); } catch (e) {}
  }
  return ids.size;
}
